import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { REPO_ROOT } from "./lib/git.mjs";
import { isMain } from "./lib/cli.mjs";

export const PAGE = "project-guide/handoff/STRUCTURE-SWEEP.md";
export const POOL = "project-guide/handoff/shared/structure-sweep/pool.tsv";
export const UNITS = "project-guide/handoff/shared/structure-sweep/units.tsv";

const POOL_STATUSES = ["landed", "in flight", "open", "closed", "waits on Andrew"];
const NEEDS_REASON = ["closed", "waits on Andrew"];
const UNIT_STAGES = ["landed", "in review", "with writer"];
const UNIT_ID = /(?<![A-Za-z0-9-])[A-Z][0-9](?![A-Za-z0-9])/g;
const LINE_CITATION = /\blines? [0-9]+/;
const FIX = "node scripts/structure-sweep.mjs --write";
const NO_LINES =
  "a line number goes stale when another unit lands, so name the function or give a `git grep` pattern instead";

function parseTsv(text) {
  const [head, ...rows] = text.split("\n").filter((line) => line.length);
  const names = head.split("\t");
  return rows.map((row, index) => {
    const cells = row.split("\t");
    const record = { line: index + 2 };
    names.forEach((name, column) => (record[name] = (cells[column] ?? "").trim()));
    return record;
  });
}

function unitsNamed(text) {
  return [...new Set(text.match(UNIT_ID) ?? [])];
}

function block(name, body) {
  return `<!-- sweep:${name}:start (generated by ${FIX}; edit pool.tsv or units.tsv, not these lines) -->\n${body}\n<!-- sweep:${name}:end -->`;
}

function blockPattern(name) {
  return new RegExp(`<!-- sweep:${name}:start[^\\n]*-->\\n[\\s\\S]*?\\n<!-- sweep:${name}:end -->`);
}

function poolRowsOf(unit, pool) {
  return pool
    .filter((row) => unitsNamed(row.unit).includes(unit))
    .map((row) => (unitsNamed(row.unit).join(", ") === row.unit ? row.id : `${row.id} (part)`));
}

export function render(pool, units) {
  const count = (status) => pool.filter((row) => row.status === status).length;
  const stage = (name) => units.filter((unit) => unit.stage === name).length;
  const leads = pool.filter((row) => row.id.startsWith("LEAD-")).length;
  const counts =
    `Of the ${pool.length} items in the pool (${pool.length - leads} survey findings and ${leads} leads), ` +
    `${count("landed")} have landed, ${count("in flight")} are with a unit, ${count("open")} are open, ` +
    `${count("waits on Andrew")} wait on Andrew and ${count("closed")} are closed. Of the ${units.length} units, ` +
    `${stage("landed")} have landed, ${stage("in review")} are in review and ` +
    `${stage("with writer")} are with their writers.`;
  const rounds = [
    "| Unit | What it did | Pool rows | Writer | Pull request | Stage | Notes |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...units.map((unit) =>
      [
        "",
        unit.unit,
        unit.what,
        poolRowsOf(unit.unit, pool).join(", ") || "none",
        unit.writer,
        unit["pull request"],
        unit.stage,
        unit.notes,
        "",
      ]
        .join(" | ")
        .trim(),
    ),
  ].join("\n");
  return { counts, rounds };
}

export function check({ page, pool, units }) {
  const findings = [];
  const fail = (file, line, message) => findings.push({ level: "failure", file, line, message });
  const stageOf = new Map(units.map((unit) => [unit.unit, unit.stage]));

  for (const unit of units) {
    if (!UNIT_STAGES.includes(unit.stage))
      fail(
        UNITS,
        unit.line,
        `unit ${unit.unit} has stage "${unit.stage}"; use one of: ${UNIT_STAGES.join(", ")}`,
      );
    if (unit.stage !== "with writer" && !/^[0-9]+$/.test(unit["pull request"]))
      fail(
        UNITS,
        unit.line,
        `unit ${unit.unit} is "${unit.stage}" and names no pull request number`,
      );
  }

  for (const row of pool) {
    const named = unitsNamed(row.unit);
    const unfinished = named.filter((unit) => stageOf.get(unit) !== "landed");
    for (const unit of named)
      if (!stageOf.has(unit))
        fail(
          POOL,
          row.line,
          `${row.id} names unit ${unit}, which has no row in ${UNITS}; add the unit there`,
        );
    if (!POOL_STATUSES.includes(row.status)) {
      fail(
        POOL,
        row.line,
        `${row.id} has status "${row.status}"; use one of: ${POOL_STATUSES.join("; ")}`,
      );
    } else if (row.status === "landed" && (named.length === 0 || unfinished.length)) {
      fail(
        POOL,
        row.line,
        named.length
          ? `${row.id} is "landed" but names ${unfinished.join(", ")}, which has not landed; set the status to "in flight"`
          : `${row.id} is "landed" and names no unit; name the unit that landed it`,
      );
    } else if (row.status === "in flight" && unfinished.length === 0) {
      fail(
        POOL,
        row.line,
        `${row.id} is "in flight" but every unit it names has landed; set the status to "landed", or to "open" if part of it is left`,
      );
    } else if (row.status !== "landed" && row.status !== "in flight" && unfinished.length) {
      fail(
        POOL,
        row.line,
        `${row.id} is "${row.status}" but names ${unfinished.join(", ")}, which has not landed; set the status to "in flight"`,
      );
    } else if (NEEDS_REASON.includes(row.status) && !page.includes(row.id)) {
      fail(
        POOL,
        row.line,
        `${row.id} is "${row.status}" and ${PAGE} does not name it; give its reason there`,
      );
    }
    const cited = row.id.startsWith("LEAD-") && LINE_CITATION.exec(row.finding);
    if (cited) fail(POOL, row.line, `${row.id} says "${cited[0]}"; ${NO_LINES}`);
  }

  const generated = render(pool, units);
  for (const name of ["counts", "rounds"]) {
    const found = blockPattern(name).exec(page);
    if (!found) fail(PAGE, 1, `the page has no "sweep:${name}" block; run ${FIX}`);
    else if (found[0] !== block(name, generated[name]))
      fail(
        PAGE,
        page.slice(0, found.index).split("\n").length,
        `the "${name}" block does not match pool.tsv and units.tsv; run ${FIX}`,
      );
  }

  page.split("\n").forEach((line, index) => {
    const found = LINE_CITATION.exec(line);
    if (found) fail(PAGE, index + 1, `the page says "${found[0]}"; ${NO_LINES}`);
  });
  return findings;
}

export function load(root) {
  return {
    page: readFileSync(path.join(root, PAGE), "utf8"),
    pool: parseTsv(readFileSync(path.join(root, POOL), "utf8")),
    units: parseTsv(readFileSync(path.join(root, UNITS), "utf8")),
  };
}

export function checkSweep(root) {
  if (!existsSync(path.join(root, PAGE))) return [];
  return check(load(root));
}

export function write(root) {
  const { page, pool, units } = load(root);
  const generated = render(pool, units);
  let next = page;
  for (const name of ["counts", "rounds"]) {
    if (!blockPattern(name).test(next))
      throw new Error(`${PAGE} has no "sweep:${name}" block to fill`);
    next = next.replace(blockPattern(name), () => block(name, generated[name]));
  }
  if (next !== page) writeFileSync(path.join(root, PAGE), next);
  return next !== page;
}

if (isMain(import.meta.url)) {
  if (process.argv.includes("--write"))
    console.log(write(REPO_ROOT) ? `rewrote ${PAGE}` : `${PAGE} already current`);
  const findings = checkSweep(REPO_ROOT);
  for (const finding of findings)
    console.log(`FAILURE ${finding.file}:${finding.line} ${finding.message}`);
  console.log(`structure-sweep ${findings.length ? "fail" : "pass"}: ${findings.length} findings`);
  process.exitCode = findings.length ? 1 : 0;
}
