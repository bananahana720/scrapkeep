import assert from "node:assert/strict";
import { test } from "node:test";

import { PAGE, POOL, UNITS, check, checkSweep, render } from "./structure-sweep.mjs";
import { REPO_ROOT } from "./lib/git.mjs";

const unit = (name, stage, pr = "1300") => ({
  line: 2,
  unit: name,
  what: `what ${name} did`,
  writer: "Gemini 4 Neon, high",
  "pull request": pr,
  stage,
  notes: "",
});
const row = (id, status, units = "", finding = "a finding") => ({
  line: 2,
  id,
  status,
  unit: units,
  "pull request": "",
  finding,
});
const blockOf = (name, body) =>
  `<!-- sweep:${name}:start (generated by node scripts/structure-sweep.mjs --write; edit pool.tsv or units.tsv, not these lines) -->\n${body}\n<!-- sweep:${name}:end -->`;
function pageFor(pool, units, extra = "") {
  const generated = render(pool, units);
  return `# Sweep\n\n${blockOf("counts", generated.counts)}\n\n${extra}\n\n${blockOf("rounds", generated.rounds)}\n`;
}
const messages = (pool, units, page = pageFor(pool, units)) =>
  check({ page, pool, units }).map((finding) => `${finding.file}: ${finding.message}`);

test("a page that matches its data files has no finding", () => {
  const units = [unit("M2", "landed"), unit("B4", "with writer", "")];
  const pool = [
    row("COMBAT-01", "landed", "M2"),
    row("COMBAT-17", "in flight", "M2 did the first half, B4 the rest"),
  ];
  assert.deepEqual(messages(pool, units), []);
});

test("an open row that names a unit still with its writer is refused", () => {
  const units = [unit("M2", "landed"), unit("B4", "with writer", "")];
  const pool = [row("COMBAT-17", "open", "M2 did the first half, B4 the rest")];
  assert.deepEqual(messages(pool, units), [
    `${POOL}: COMBAT-17 is "open" but names B4, which has not landed; set the status to "in flight"`,
  ]);
});

test("a landed row needs a landed unit, and an in-flight row an unfinished one", () => {
  const units = [unit("M2", "landed"), unit("B4", "in review")];
  const found = messages(
    [row("A-01", "landed", "B4"), row("A-02", "landed"), row("A-03", "in flight", "M2")],
    units,
  );
  assert.equal(found.length, 3);
  assert.match(found[0], /A-01 is "landed" but names B4/);
  assert.match(found[1], /A-02 is "landed" and names no unit/);
  assert.match(found[2], /A-03 is "in flight" but every unit it names has landed/);
});

test("a status outside the list, a unit with no row and a missing pull request are refused", () => {
  const found = messages(
    [row("A-01", "waits on Andrew (decision)"), row("A-02", "in flight", "Z9")],
    [unit("M2", "merged"), unit("N3", "in review", "")],
  );
  assert.ok(
    found.some((message) => /A-01 has status "waits on Andrew \(decision\)"/.test(message)),
  );
  assert.ok(found.some((message) => /A-02 names unit Z9, which has no row/.test(message)));
  assert.ok(found.some((message) => /unit M2 has stage "merged"/.test(message)));
  assert.ok(
    found.some((message) =>
      /unit N3 is "in review" and names no pull request number/.test(message),
    ),
  );
});

test("a closed or waiting row must be named on the page, where its reason goes", () => {
  const units = [unit("M2", "landed")];
  const pool = [row("UI-05", "closed"), row("DOC-03", "waits on Andrew")];
  const found = messages(
    pool,
    units,
    pageFor(pool, units, "UI-05 is closed because the HUD owns four of its inputs."),
  );
  assert.deepEqual(found, [
    `${POOL}: DOC-03 is "waits on Andrew" and ${PAGE} does not name it; give its reason there`,
  ]);
});

test("a line number is refused in the page and in a lead", () => {
  const units = [unit("M2", "landed")];
  const pool = [row("LEAD-01", "open", "", "`combat.gd` line 310 still reads the private queue")];
  const found = messages(
    pool,
    units,
    pageFor(pool, units, "Checked: `flow.gd` lines 40 to 52 hold the guard."),
  );
  assert.equal(found.length, 2);
  assert.match(found[0], /LEAD-01 says "line 310"; a line number goes stale/);
  assert.match(found[1], /the page says "lines 40"/);
});

test("a hand-edited count or table is refused and names the command that rewrites it", () => {
  const units = [unit("M2", "landed")];
  const pool = [row("A-01", "landed", "M2")];
  const stale = pageFor(pool, units).replace("1 landed", "2 landed");
  assert.deepEqual(messages(pool, units, stale), [
    `${PAGE}: the "counts" block does not match pool.tsv and units.tsv; run node scripts/structure-sweep.mjs --write`,
  ]);
  assert.match(messages(pool, units, "# Sweep\n")[0], /the page has no "sweep:counts" block/);
});

test("the table lists each unit's pool rows, marking a row several units share", () => {
  const units = [unit("M2", "landed"), unit("B4", "with writer", "")];
  const pool = [
    row("A-01", "landed", "M2"),
    row("A-02", "in flight", "M2 the first half, B4 the rest"),
  ];
  const { rounds, counts } = render(pool, units);
  assert.match(rounds, /\| M2 \| what M2 did \| A-01, A-02 \(part\) \|/);
  assert.match(rounds, /\| B4 \| what B4 did \| A-02 \(part\) \|/);
  assert.match(
    counts,
    /^The pool holds 2 items \(2 survey findings and 0 leads\): 1 landed, 1 with a unit/,
  );
});

test("the repository's own page agrees with its data files", () => {
  assert.deepEqual(checkSweep(REPO_ROOT), []);
  assert.ok(UNITS.endsWith("units.tsv"));
});
