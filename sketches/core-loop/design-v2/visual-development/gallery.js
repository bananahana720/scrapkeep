const select = document.getElementById('sheet');
const catalog = document.getElementById('catalog');
let active = 0;
atlas.forEach((item, index) => {
  const option = document.createElement('option');
  option.value = String(index);
  option.textContent = item.title;
  select.append(option);
  const button = document.createElement('button');
  button.type = 'button';
  button.className = 'tile';
  button.setAttribute('aria-pressed', 'false');
  const img = document.createElement('img');
  img.src = 'images/' + item.file;
  img.alt = '';
  img.loading = 'lazy';
  const label = document.createElement('span');
  label.textContent = item.title;
  button.append(img, label);
  button.addEventListener('click', () => show(index));
  catalog.append(button);
});
function show(index) {
  active = (index + atlas.length) % atlas.length;
  const item = atlas[active];
  select.value = String(active);
  document.getElementById('preview').src = 'images/' + item.file;
  document.getElementById('preview').alt = item.title + '. ' + item.note;
  document.getElementById('title').textContent = item.title;
  document.getElementById('status').textContent = item.status;
  document.getElementById('note').textContent = item.note;
  document.getElementById('original').href = 'images/' + item.file;
  catalog.querySelectorAll('button').forEach((button, i) => button.setAttribute('aria-pressed', String(i === active)));
  history.replaceState(null, '', '#' + item.id);
}
select.addEventListener('change', () => show(Number(select.value)));
document.getElementById('previous').addEventListener('click', () => show(active - 1));
document.getElementById('next').addEventListener('click', () => show(active + 1));
const initial = atlas.findIndex(item => item.id === location.hash.slice(1));
show(initial < 0 ? 0 : initial);
